def split_validated_rows(
    final_rows: List[Dict[str, Any]],
    final_warnings: List[str],
    final_has_hard_error: bool,
    include_validation_warnings: bool,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Split validated rows into success rows and failed rows.

    This helper is used by both serial and concurrent execution. It keeps
    --output success-only and sends failed rows to --failed-output.
    """
    warning_text_by_pid: Dict[str, List[str]] = {}
    for w in final_warnings:
        m = re.match(r"paper_id=([^:]+):\s*(.*)", w)
        if m:
            warning_text_by_pid.setdefault(m.group(1), []).append(m.group(2))

    success_rows: List[Dict[str, Any]] = []
    failed_rows: List[Dict[str, Any]] = []
    batch_level_failure = final_has_hard_error and any(
        (not w.startswith("paper_id=")) for w in final_warnings
    )

    for row in final_rows:
        row_failed = bool(row.pop("_validation_hard_error", False)) or batch_level_failure
        if row_failed:
            row["validation_failed_after_retries"] = True
            row["failure_type"] = "validation_failed_after_retries"
            if "validation_warnings" not in row:
                row["validation_warnings"] = warning_text_by_pid.get(str(row.get("paper_id", "")), [])
            if batch_level_failure:
                row.setdefault(
                    "batch_validation_warnings",
                    [w for w in final_warnings if not w.startswith("paper_id=")],
                )
            failed_rows.append(row)
        else:
            row.pop("validation_failed_after_retries", None)
            row.pop("validation_warnings", None) if not include_validation_warnings else None
            success_rows.append(row)

    return success_rows, failed_rows


def make_api_failed_rows(
    task: BatchTask,
    paper_candidates: Dict[str, List[L3Topic]],
    matched_l2_map: Dict[str, Optional[str]],
    pre_warnings: Dict[str, Optional[str]],
    args: argparse.Namespace,
    error_message: str,
) -> List[Dict[str, Any]]:
    """Create failed-output rows when the API/JSON call fails completely."""
    failed_rows: List[Dict[str, Any]] = []
    for paper in task.batch_for_llm:
        pid = str(paper.get("paper_id", ""))
        row, warnings, _ = validate_one_paper(
            paper=paper,
            model_item=None,
            candidates=paper_candidates[pid],
            include_description_in_output=args.include_description_in_output,
            include_validation_warnings=True,
            include_canonical_topic=args.include_canonical_topic,
            matched_l2=matched_l2_map.get(pid),
            pre_warning=pre_warnings.get(pid),
        )
        row.pop("_validation_hard_error", None)
        row["validation_failed_after_retries"] = True
        row["failure_type"] = "api_or_json_failed_after_retries"
        row["validation_warnings"] = warnings + [error_message]
        failed_rows.append(row)
    return failed_rows


def process_llm_batch(
    task: BatchTask,
    args: argparse.Namespace,
    matched_l2_map: Dict[str, Optional[str]],
    pre_warnings: Dict[str, Optional[str]],
) -> BatchResult:
    """Run one LLM batch.

    This function is intentionally self-contained so it can run inside a
    ThreadPoolExecutor worker. Each worker creates its own OpenAI client instead
    of sharing one client across threads.
    """
    if OpenAI is None:
        raise RuntimeError("Missing dependency: pip install openai")

    client = OpenAI(api_key=args.api_key, base_url=args.base_url)
    paper_candidates: Dict[str, List[L3Topic]] = {
        str(p.get("paper_id", "")): task.shared_candidates for p in task.batch_for_llm
    }
    prompt_papers = build_prompt_papers(task.batch_for_llm, args.max_abstract_chars)

    final_rows: Optional[List[Dict[str, Any]]] = None
    final_warnings: List[str] = []
    final_has_hard_error = False
    used_rf = False
    worker_warnings: List[str] = []

    for validation_attempt in range(1, args.max_validation_attempts + 1):
        # Reuse the same prompt on validation retries. Do not feed previous error details back to the model.
        messages = build_messages(prompt_papers, task.shared_candidates)

        last_exc: Optional[Exception] = None
        llm_obj: Optional[Dict[str, Any]] = None
        used_rf = False

        for api_attempt in range(1, args.max_api_retries + 1):
            try:
                llm_obj, _raw_text, used_rf = call_llm(
                    client=client,
                    model=args.model,
                    messages=messages,
                    temperature=args.temperature,
                    max_tokens=args.max_tokens,
                    response_format_mode=args.response_format_mode,
                )
                break
            except Exception as e:  # noqa: BLE001
                last_exc = e
                worker_warnings.append(
                    f"API/JSON call failed call={task.call_index} l2_group={task.l2_index} "
                    f"batch={task.local_batch_index} api_attempt={api_attempt}/{args.max_api_retries}: {e}"
                )
                if api_attempt < args.max_api_retries:
                    wait = min(2 ** (api_attempt - 1), 20)
                    time.sleep(wait)

        if llm_obj is None:
            err = f"LLM call failed after retries: {last_exc}"
            failed_rows = make_api_failed_rows(
                task=task,
                paper_candidates=paper_candidates,
                matched_l2_map=matched_l2_map,
                pre_warnings=pre_warnings,
                args=args,
                error_message=err,
            )
            if args.sleep > 0:
                time.sleep(args.sleep)
            return BatchResult(
                call_index=task.call_index,
                l2_index=task.l2_index,
                total_l2_groups=task.total_l2_groups,
                local_batch_index=task.local_batch_index,
                success_rows=[],
                failed_rows=failed_rows,
                warnings=worker_warnings + [err],
                info=(
                    f"call={task.call_index} l2_group={task.l2_index}/{task.total_l2_groups} "
                    f"batch={task.local_batch_index} wrote success=0 to output, "
                    f"failed={len(failed_rows)} to failed_output; response_format_used={used_rf}"
                ),
                response_format_used=used_rf,
            )

        # On the final failed attempt, always store warnings in failed rows so the failure is recorded.
        store_warnings_this_attempt = args.include_validation_warnings or validation_attempt == args.max_validation_attempts

        rows, warnings, has_hard_error = validate_batch(
            batch=task.batch_for_llm,
            llm_obj=llm_obj,
            paper_candidates=paper_candidates,
            include_description_in_output=args.include_description_in_output,
            include_validation_warnings=store_warnings_this_attempt,
            include_canonical_topic=args.include_canonical_topic,
            matched_l2_map=matched_l2_map,
            pre_warnings=pre_warnings,
        )
        final_rows = rows
        final_warnings = warnings
        final_has_hard_error = has_hard_error

        if not has_hard_error:
            break

        if validation_attempt < args.max_validation_attempts:
            worker_warnings.append(
                f"validation failed call={task.call_index}; retrying "
                f"validation_attempt={validation_attempt + 1}/{args.max_validation_attempts}"
            )

    if final_rows is None:
        raise RuntimeError("internal error: final_rows is None")

    success_rows, failed_rows = split_validated_rows(
        final_rows=final_rows,
        final_warnings=final_warnings,
        final_has_hard_error=final_has_hard_error,
        include_validation_warnings=args.include_validation_warnings,
    )

    if args.sleep > 0:
        time.sleep(args.sleep)

    return BatchResult(
        call_index=task.call_index,
        l2_index=task.l2_index,
        total_l2_groups=task.total_l2_groups,
        local_batch_index=task.local_batch_index,
        success_rows=success_rows,
        failed_rows=failed_rows,
        warnings=worker_warnings + final_warnings,
        info=(
            f"call={task.call_index} l2_group={task.l2_index}/{task.total_l2_groups} "
            f"batch={task.local_batch_index} wrote success={len(success_rows)} to output, "
            f"failed={len(failed_rows)} to failed_output; response_format_used={used_rf}"
        ),
        response_format_used=used_rf,
    )


def write_batch_result(result: BatchResult, output_path: str, failed_output_path: str) -> None:
    """Write one completed batch result from the main thread only."""
    if result.success_rows:
        append_jsonl(output_path, result.success_rows)
    if result.failed_rows:
        append_jsonl(failed_output_path, result.failed_rows)

    for w in result.warnings:
        print(f"[warn] {w}", file=sys.stderr)
    print(f"[info] {result.info}", file=sys.stderr)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Classify papers into L3 topics using an OpenAI-compatible API."
    )
    parser.add_argument("--topics", required=True, help="Path to ml_l3_topics_all.jsonl")
    parser.add_argument("--input", required=True, help="Path to paper JSONL, e.g. iclr2026_rejected_topics_map.jsonl")
    parser.add_argument("--output", required=True, help="Success-only output JSONL path")
    parser.add_argument(
        "--failed-output",
        default=None,
        help="Failed-record JSONL path. Default: <output>.failed.jsonl. Failed records are never written to --output.",
    )

    # No provider argument by design. User supplies base URL directly.
    parser.add_argument(
        "--base-url",
        default=os.getenv("LLM_BASE_URL") or os.getenv("OPENAI_BASE_URL") or "https://api.openai.com/v1",
        help="OpenAI-compatible base URL, e.g. https://api.deepseek.com/v1, https://api.minimax.io/v1, https://openrouter.ai/api/v1",
    )
    parser.add_argument(
        "--api-key",
        default=os.getenv("LLM_API_KEY") or os.getenv("OPENAI_API_KEY") or "EMPTY",
        help="API key. Can also use LLM_API_KEY or OPENAI_API_KEY. For local endpoints, EMPTY is okay if accepted.",
    )
    parser.add_argument(
        "--model",
        default=os.getenv("LLM_MODEL") or os.getenv("OPENAI_MODEL"),
        help="Model name, e.g. deepseek-chat, MiniMax-M1, gpt-4.1-mini, openai/gpt-4.1-mini. Can also use LLM_MODEL.",
    )

    parser.add_argument("--batch-size", type=int, default=5, help="Number of papers per LLM call. Default: 5")
    parser.add_argument("--limit", type=int, default=0, help="Classify only first N remaining papers. 0 means all.")
    parser.add_argument("--temperature", type=float, default=0.0)
    parser.add_argument("--max-tokens", type=int, default=4096)
    parser.add_argument("--max-abstract-chars", type=int, default=4000)
    parser.add_argument("--sleep", type=float, default=0.0, help="Sleep seconds after each API call")
    parser.add_argument(
        "--concurrency",
        type=int,
        default=3,
        help="Number of concurrent LLM batch requests. Default: 1. Use 3 to send three requests at once.",
    )

    parser.add_argument(
        "--response-format-mode",
        choices=["auto", "on", "off"],
        default="auto",
        help="Use response_format={type:json_object}. auto retries without it if unsupported. Default: auto",
    )
    parser.add_argument("--max-api-retries", type=int, default=3)
    parser.add_argument(
        "--max-validation-attempts",
        type=int,
        default=3,
        help=(
            "Total validation attempts for a batch. If id/name_en pairs are not exact, "
            "the script asks the LLM to regenerate. After this many failed attempts, "
            "it records validation_failed_after_retries=true and writes warnings. Default: 3"
        ),
    )

    parser.add_argument("--dry-run", action="store_true", help="Print one prompt batch and exit without calling LLM")
    parser.add_argument("--print-config", action="store_true", help="Print resolved config and continue")
    parser.add_argument("--force", action="store_true", help="Do not skip paper_ids already in output")
    parser.add_argument(
        "--include-description-in-output",
        action="store_true",
        help="Also include description_en in L3topic_detail output. By default output detail only has id/name_en.",
    )
    parser.add_argument(
        "--include-validation-warnings",
        action="store_true",
        help=(
            "Write validation_warnings into output rows whenever there are warnings. "
            "Even if this flag is not set, warnings are still written for batches that fail all validation attempts."
        ),
    )
    parser.add_argument(
        "--include-canonical-topic",
        action="store_true",
        help="Copy canonical_topic from input into output for debugging. It is never produced by the LLM.",
    )

    return parser.parse_args()


def main() -> int:
    args = parse_args()

    if not args.failed_output:
        args.failed_output = args.output + ".failed.jsonl"

    if args.batch_size <= 0:
        raise SystemExit("--batch-size must be positive")
    if args.concurrency <= 0:
        raise SystemExit("--concurrency must be positive")
    if args.max_validation_attempts <= 0:
        raise SystemExit("--max-validation-attempts must be positive")
    if not args.model:
        raise SystemExit("Missing --model. Provide --model or set LLM_MODEL / OPENAI_MODEL.")
    if OpenAI is None and not args.dry_run:
        raise SystemExit("Missing dependency: pip install openai")

    if args.print_config:
        redacted_key = "EMPTY" if args.api_key == "EMPTY" else (args.api_key[:4] + "..." + args.api_key[-4:])
        print(
            json.dumps(
                {
                    "base_url": args.base_url,
                    "api_key": redacted_key,
                    "model": args.model,
                    "batch_size": args.batch_size,
                    "concurrency": args.concurrency,
                    "batching_strategy": "group_by_L2_then_batch",
                    "response_format_mode": args.response_format_mode,
                    "success_output": args.output,
                    "failed_output": args.failed_output,
                },
                ensure_ascii=False,
                indent=2,
            )
        )

    l2_to_l3, norm_to_exact_l2 = load_l3_topics(args.topics)
    if not l2_to_l3:
        raise SystemExit(f"No L3 topics loaded from {args.topics}")

    all_papers = list(read_jsonl(args.input))
    if not all_papers:
        raise SystemExit(f"No papers loaded from {args.input}")

    if args.force:
        done_ids: set[str] = set()
        resume_stats: Dict[str, Any] = {
            "existing_rows": 0,
            "done_rows": 0,
            "migrated_failed_rows": 0,
            "invalid_rows": 0,
            "failed_output_path": args.failed_output,
        }
    else:
        done_ids, resume_stats = load_done_ids(args.output, args.failed_output)

    remaining: List[Dict[str, Any]] = []
    for p in all_papers:
        pid = str(p.get("paper_id", ""))
        if not pid:
            print("[warn] skip paper without paper_id", file=sys.stderr)
            continue
        if pid in done_ids:
            continue
        remaining.append(p)

    if args.limit and args.limit > 0:
        remaining = remaining[: args.limit]

    if resume_stats.get("migrated_failed_rows"):
        print(
            f"[info] migrated {resume_stats['migrated_failed_rows']} old failed rows from output "
            f"to failed_output={args.failed_output}; those papers will be retried",
            file=sys.stderr,
        )

    print(
        f"[info] loaded {len(all_papers)} papers; already done successful {len(done_ids)}; to process {len(remaining)}",
        file=sys.stderr,
    )

    if not remaining:
        print("[info] nothing to do", file=sys.stderr)
        return 0

    # ------------------------------------------------------------------
    # Group papers by matched L2 topic before batching.
    #
    # This is the key optimization requested by the user:
    #   - each LLM call contains only papers from the same L2 topic;
    #   - the candidate L3 list for that L2 is sent once in the system prompt;
    #   - the user prompt contains only the papers in that batch.
    #
    # We preserve first-seen L2 order from the input file. If a group size is
    # not divisible by --batch-size, its final smaller batch is still sent as-is.
    # ------------------------------------------------------------------
    grouped_papers: Dict[str, List[Dict[str, Any]]] = {}
    group_order: List[str] = []
    l2_candidates: Dict[str, List[L3Topic]] = {}
    matched_l2_map: Dict[str, Optional[str]] = {}
    pre_warnings: Dict[str, Optional[str]] = {}
    skipped_missing_candidates = 0
    direct_failed_rows: List[Dict[str, Any]] = []

    for p in remaining:
        pid = str(p.get("paper_id", ""))
        candidates, matched_l2, warn = find_l3_candidates(p, l2_to_l3, norm_to_exact_l2)
        matched_l2_map[pid] = matched_l2
        pre_warnings[pid] = warn

        if not candidates or not matched_l2:
            skipped_missing_candidates += 1
            row, _, _ = validate_one_paper(
                paper=p,
                model_item={"paper_id": pid, "selected_L3_topics": []},
                candidates=[],
                include_description_in_output=args.include_description_in_output,
                include_validation_warnings=args.include_validation_warnings,
                include_canonical_topic=args.include_canonical_topic,
                matched_l2=matched_l2,
                pre_warning=warn,
            )
            row["validation_failed_after_retries"] = True
            row["failure_type"] = "no_candidate_l3_topics"
            if "validation_warnings" not in row:
                row["validation_warnings"] = [warn or "no candidate L3 topics found"]
            direct_failed_rows.append(row)
            continue

        if matched_l2 not in grouped_papers:
            grouped_papers[matched_l2] = []
            group_order.append(matched_l2)
            l2_candidates[matched_l2] = candidates
        grouped_papers[matched_l2].append(p)

    if direct_failed_rows:
        append_jsonl(args.failed_output, direct_failed_rows)
        for r in direct_failed_rows:
            print(
                f"[warn] wrote failed record for paper_id={r['paper_id']} to failed_output because no candidate L3 topics were found",
                file=sys.stderr,
            )

    total_llm_papers = sum(len(grouped_papers[g]) for g in group_order)
    print(
        f"[info] grouped remaining papers into {len(group_order)} L2 groups; "
        f"LLM papers={total_llm_papers}; direct_failed_no_candidates={len(direct_failed_rows)}",
        file=sys.stderr,
    )

    tasks: List[BatchTask] = []
    call_index = 0

    for l2_index, l2_key in enumerate(group_order, start=1):
        group = grouped_papers[l2_key]
        shared_candidates = l2_candidates[l2_key]
        print(
            f"[info] L2 group {l2_index}/{len(group_order)}: papers={len(group)}, "
            f"candidate_L3={len(shared_candidates)}",
            file=sys.stderr,
        )

        for local_batch_index, batch_for_llm in enumerate(batched(group, args.batch_size), start=1):
            call_index += 1
            tasks.append(
                BatchTask(
                    call_index=call_index,
                    l2_index=l2_index,
                    total_l2_groups=len(group_order),
                    l2_key=l2_key,
                    local_batch_index=local_batch_index,
                    batch_for_llm=batch_for_llm,
                    shared_candidates=shared_candidates,
                )
            )

    if not tasks:
        print("[info] no LLM batches to process", file=sys.stderr)
    elif args.dry_run:
        first_task = tasks[0]
        prompt_papers = build_prompt_papers(first_task.batch_for_llm, args.max_abstract_chars)
        messages = build_messages(prompt_papers, first_task.shared_candidates)
        print(json.dumps({"messages": messages}, ensure_ascii=False, indent=2))
        print("\n[dry-run] no API call made; no output written for LLM batch", file=sys.stderr)
        return 0
    else:
        max_workers = min(args.concurrency, len(tasks))
        print(
            f"[info] prepared {len(tasks)} LLM batches; concurrency={max_workers}",
            file=sys.stderr,
        )

        # Write in call_index order for deterministic output, while still running API calls concurrently.
        completed_by_index: Dict[int, BatchResult] = {}
        next_to_write = 1

        if max_workers == 1:
            for task in tasks:
                result = process_llm_batch(
                    task=task,
                    args=args,
                    matched_l2_map=matched_l2_map,
                    pre_warnings=pre_warnings,
                )
                write_batch_result(result, args.output, args.failed_output)
        else:
            with ThreadPoolExecutor(max_workers=max_workers) as executor:
                future_to_call_index = {
                    executor.submit(
                        process_llm_batch,
                        task,
                        args,
                        matched_l2_map,
                        pre_warnings,
                    ): task.call_index
                    for task in tasks
                }

                for future in as_completed(future_to_call_index):
                    result = future.result()
                    completed_by_index[result.call_index] = result

                    while next_to_write in completed_by_index:
                        ordered_result = completed_by_index.pop(next_to_write)
                        write_batch_result(ordered_result, args.output, args.failed_output)
                        next_to_write += 1

    if skipped_missing_candidates:
        print(f"[warn] {skipped_missing_candidates} papers had no candidate L3 topics", file=sys.stderr)

    print(f"[info] done. success_output={args.output}; failed_output={args.failed_output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
