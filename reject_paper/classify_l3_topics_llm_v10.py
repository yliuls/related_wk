def normalize_selected_topics(value: Any) -> List[Dict[str, str]]:
    """Accept the intended schema, plus a few common malformed variants."""
    if value is None:
        return []
    if isinstance(value, dict):
        value = [value]
    if not isinstance(value, list):
        return []

    out: List[Dict[str, str]] = []
    for item in value:
        if isinstance(item, dict):
            tid = norm_text(item.get("id") or item.get("topic_id") or item.get("L3topic_id"))
            name = norm_text(item.get("name_en") or item.get("topic_name_en") or item.get("name") or item.get("L3topic"))
            out.append({"id": tid, "name_en": name})
        elif isinstance(item, str):
            s = norm_text(item)
            out.append({"id": s, "name_en": s})
    return out


def validate_one_paper(
    paper: Dict[str, Any],
    model_item: Optional[Dict[str, Any]],
    candidates: List[L3Topic],
    include_description_in_output: bool,
    include_validation_warnings: bool,
    include_canonical_topic: bool,
    matched_l2: Optional[str],
    pre_warning: Optional[str] = None,
) -> Tuple[Dict[str, Any], List[str], bool]:
    """Validate LLM topic id/name_en pairs strictly.

    Important behavior:
      - If id is correct but name_en is missing/wrong, mark hard_error=True.
      - If name_en is correct but id is missing/wrong, mark hard_error=True.
      - The returned row still uses the canonical candidate table to produce a clean final output,
        but the hard error forces the caller to ask the LLM to regenerate until attempts are exhausted.

    Returns: (output_row, warnings, has_hard_error)
    has_hard_error means we should retry if possible.
    """
    pid = str(paper.get("paper_id", ""))
    warnings: List[str] = []
    hard_error = False
    if pre_warning:
        warnings.append(pre_warning)

    id_map = {t.id: t for t in candidates}
    # exact English name -> topic
    name_map = {t.name_en: t for t in candidates}
    # lower/normalized English name -> topic, only if unique
    norm_name_to_topics: Dict[str, List[L3Topic]] = {}
    for t in candidates:
        norm_name_to_topics.setdefault(norm_key(t.name_en), []).append(t)

    if model_item is None:
        selected_raw: Any = []
        warnings.append("LLM output missing this paper_id; selected_L3_topics set to empty")
        hard_error = True
    else:
        selected_raw = (
            model_item.get("selected_L3_topics")
            if "selected_L3_topics" in model_item
            else model_item.get("L3topic_ids")
            if "L3topic_ids" in model_item
            else model_item.get("L3topic")
        )

    selected = normalize_selected_topics(selected_raw)
    fixed_topics: List[L3Topic] = []
    seen_ids: set[str] = set()

    for st in selected:
        raw_id = norm_text(st.get("id"))
        raw_name = norm_text(st.get("name_en"))
        topic: Optional[L3Topic] = None

        if raw_id in id_map:
            topic = id_map[raw_id]
            if raw_name != topic.name_en:
                warnings.append(
                    f"topic id/name_en mismatch: id={raw_id!r} is valid, "
                    f"but LLM name_en={raw_name!r}; expected name_en={topic.name_en!r}"
                )
                hard_error = True
        elif raw_name in name_map:
            topic = name_map[raw_name]
            warnings.append(
                f"topic name_en/id mismatch: name_en={raw_name!r} is valid, "
                f"but LLM id={raw_id!r}; expected id={topic.id!r}"
            )
            hard_error = True
        else:
            norm_name = norm_key(raw_name)
            maybe = norm_name_to_topics.get(norm_name, [])
            if len(maybe) == 1:
                topic = maybe[0]
                warnings.append(
                    f"topic name_en/id mismatch after normalization: name_en={raw_name!r} maps to "
                    f"expected id={topic.id!r}, expected name_en={topic.name_en!r}; LLM id={raw_id!r}"
                )
                hard_error = True

        if topic is None:
            warnings.append(f"invalid selected L3 topic dropped: id={raw_id!r}, name_en={raw_name!r}")
            hard_error = True
            continue

        if topic.id not in seen_ids:
            fixed_topics.append(topic)
            seen_ids.add(topic.id)

    row: Dict[str, Any] = {
        "paper_id": pid,
        "title": norm_text(paper.get("title")),
        "L3topic_ids": [t.id for t in fixed_topics],
        "L3topic": [t.name_en for t in fixed_topics],
        "L3topic_detail": [t.to_output_dict(include_description=include_description_in_output) for t in fixed_topics],
    }
    if include_canonical_topic:
        # This is copied from the original file only; it is not produced by the LLM.
        row["canonical_topic"] = norm_text(paper.get("canonical_topic"))
        if matched_l2:
            row["matched_L2_for_candidate_lookup"] = matched_l2
    if include_validation_warnings and warnings:
        row["validation_warnings"] = warnings

    return row, warnings, hard_error


def validate_batch(
    batch: Sequence[Dict[str, Any]],
    llm_obj: Dict[str, Any],
    paper_candidates: Dict[str, List[L3Topic]],
    include_description_in_output: bool,
    include_validation_warnings: bool,
    include_canonical_topic: bool,
    matched_l2_map: Dict[str, Optional[str]],
    pre_warnings: Dict[str, Optional[str]],
) -> Tuple[List[Dict[str, Any]], List[str], bool]:
    papers_out = llm_obj.get("papers")
    if not isinstance(papers_out, list):
        papers_out = []

    model_by_pid: Dict[str, Dict[str, Any]] = {}
    duplicate_pids: set[str] = set()
    for item in papers_out:
        if not isinstance(item, dict):
            continue
        pid = str(item.get("paper_id", ""))
        if not pid:
            continue
        if pid in model_by_pid:
            duplicate_pids.add(pid)
        model_by_pid[pid] = item

    batch_warnings: List[str] = []
    has_hard_error = False
    rows: List[Dict[str, Any]] = []

    if duplicate_pids:
        batch_warnings.append(f"LLM returned duplicate paper_id values: {sorted(duplicate_pids)}")
        has_hard_error = True

    for p in batch:
        pid = str(p.get("paper_id", ""))
        row, warnings, hard_error = validate_one_paper(
            paper=p,
            model_item=model_by_pid.get(pid),
            candidates=paper_candidates[pid],
            include_description_in_output=include_description_in_output,
            include_validation_warnings=include_validation_warnings,
            include_canonical_topic=include_canonical_topic,
            matched_l2=matched_l2_map.get(pid),
            pre_warning=pre_warnings.get(pid),
        )
        # Internal flag used only by the main loop to split success vs failed rows.
        # It is removed before writing JSONL files.
        row["_validation_hard_error"] = hard_error
        rows.append(row)
        for w in warnings:
            batch_warnings.append(f"paper_id={pid}: {w}")
        has_hard_error = has_hard_error or hard_error

    extra_pids = sorted(set(model_by_pid) - {str(p.get("paper_id", "")) for p in batch})
    if extra_pids:
        batch_warnings.append(f"LLM returned unexpected paper_id values not in batch: {extra_pids}")
        has_hard_error = True

    return rows, batch_warnings, has_hard_error


