def norm_text(s: Any) -> str:
    return " ".join(str(s or "").strip().split())


def norm_key(s: Any) -> str:
    return norm_text(s).lower()


def short_abstract(text: str, max_chars: int) -> str:
    text = norm_text(text)
    if max_chars <= 0 or len(text) <= max_chars:
        return text
    return text[:max_chars].rstrip() + "..."


@dataclass
class L3Topic:
    id: str
    name_en: str
    description_en: str

    def to_prompt_dict(self) -> Dict[str, str]:
        return {
            "id": self.id,
            "name_en": self.name_en,
            "description_en": self.description_en,
        }

    def to_output_dict(self, include_description: bool = False) -> Dict[str, str]:
        out = {"id": self.id, "name_en": self.name_en}
        if include_description:
            out["description_en"] = self.description_en
        return out


def load_l3_topics(topic_path: str) -> Tuple[Dict[str, List[L3Topic]], Dict[str, str]]:
    """Return exact L2 -> L3 list, and normalized L2 -> exact L2."""
    l2_to_l3: Dict[str, List[L3Topic]] = {}
    norm_to_exact: Dict[str, str] = {}

    for obj in read_jsonl(topic_path):
        l2 = norm_text(obj.get("topic_L2"))
        if not l2:
            continue
        raw_topics = obj.get("topics_L3") or []
        if not isinstance(raw_topics, list):
            raise ValueError(f"topics_L3 for L2={l2!r} must be a list")

        topics: List[L3Topic] = []
        for t in raw_topics:
            if not isinstance(t, dict):
                continue
            tid = norm_text(t.get("id"))
            name_en = norm_text(t.get("name_en"))
            # The user explicitly wants description_en in the LLM input.
            # Fall back to description only if description_en is missing.
            desc_en = norm_text(t.get("description_en") or t.get("description"))
            if not tid or not name_en:
                continue
            topics.append(L3Topic(id=tid, name_en=name_en, description_en=desc_en))

        l2_to_l3[l2] = topics
        norm_to_exact[norm_key(l2)] = l2

    return l2_to_l3, norm_to_exact


def find_l3_candidates(
    paper: Dict[str, Any],
    l2_to_l3: Dict[str, List[L3Topic]],
    norm_to_exact_l2: Dict[str, str],
) -> Tuple[List[L3Topic], Optional[str], Optional[str]]:
    """Find candidate L3 topics by paper['canonical_topic'].

    Returns: (candidates, matched_l2, warning)
    matched_l2 is only for internal/debug output if requested. It is not sent to LLM.
    """
    canonical = norm_text(paper.get("canonical_topic"))
    if not canonical:
        return [], None, "missing canonical_topic"

    if canonical in l2_to_l3:
        return l2_to_l3[canonical], canonical, None

    exact = norm_to_exact_l2.get(norm_key(canonical))
    if exact and exact in l2_to_l3:
        return l2_to_l3[exact], exact, f"canonical_topic normalized from {canonical!r} to {exact!r}"

    return [], None, f"no L3 topic candidates found for canonical_topic={canonical!r}"


