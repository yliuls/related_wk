# -*- coding: utf-8 -*-
"""
Classify each paper into L3 topics using an OpenAI-compatible Chat Completions API.

Input files expected:
  1) L3 topic file: JSONL, each line like:
     {
       "topic_L2": "Probabilistic methods",
       "topics_L3": [
         {"id": "T01", "name_en": "...", "description_en": "..."}, ...
       ]
     }

  2) Paper file: JSONL, each line like:
     {
       "paper_id": "00001",
       "title": "...",
       "abstract": "...",
       "canonical_topic": "Probabilistic methods"
     }

Important design:
  - The LLM does NOT receive canonical_topic / L2 topic.
  - canonical_topic is used only inside this script to choose the candidate L3 list.
  - Papers are grouped by canonical_topic/L2 before batching.
  - Each LLM call contains papers from exactly one L2 topic.
  - Shared candidate L3 topics with id/name_en/description_en are placed once in the system prompt.
  - The user prompt contains only paper_id/title/abstract for the current batch.
  - The LLM returns ONLY L3 id + English name, no reason.
  - This script strictly validates id/name_en pairs against the candidate list.
  - If id/name_en do not exactly match, the batch is regenerated by the LLM.
  - After 3 validation attempts by default, successful rows are written to --output.
  - Failed rows are written to --failed-output, not --output.
  - Resume is supported: existing paper_id values in --output are skipped.
  - Because --output contains only successful rows, failed papers are retried on rerun.
  - Optional concurrency is supported with --concurrency. Use --concurrency 3 to run 3 LLM requests at once.

Example:
  python classify_l3_topics_llm_v10.py \
    --base-url https://api.deepseek.com/v1 \
    --api-key "$DEEPSEEK_API_KEY" \
    --model deepseek-chat \
    --topics ml_l3_topics_all.jsonl \
    --input iclr2026_rejected_topics_map.jsonl \
    --output iclr2026_rejected_l3_topics.jsonl \
    --concurrency 3

For OpenRouter / MiniMax / local OpenAI-compatible endpoints, just change --base-url and --model.
"""

