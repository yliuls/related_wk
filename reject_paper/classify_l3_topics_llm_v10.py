def read_jsonl(path: str) -> Iterable[Dict[str, Any]]:
    with open(path, "r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError as e:
                raise ValueError(f"Invalid JSON at {path}:{line_no}: {e}") from e
            if not isinstance(obj, dict):
                raise ValueError(f"Expected JSON object at {path}:{line_no}, got {type(obj).__name__}")
            yield obj


def append_jsonl(path: str, rows: Sequence[Dict[str, Any]]) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
        f.flush()
        os.fsync(f.fileno())


def load_done_ids(output_path: str, failed_output_path: str) -> Tuple[set[str], Dict[str, Any]]:
    """Load completed paper_ids from the success-only output JSONL.

    --output should contain successful rows only. If an older output file contains
    rows marked validation_failed_after_retries=true, this function migrates those
    rows into --failed-output and rewrites --output without them. Those paper_ids are
    NOT treated as done, so they will be retried on rerun.
    """
    done: set[str] = set()
    stats: Dict[str, Any] = {
        "existing_rows": 0,
        "done_rows": 0,
        "migrated_failed_rows": 0,
        "invalid_rows": 0,
        "failed_output_path": failed_output_path,
    }
    if not output_path or not os.path.exists(output_path):
        return done, stats

    success_or_kept_lines: List[str] = []
    failed_rows_to_migrate: List[Dict[str, Any]] = []

    with open(output_path, "r", encoding="utf-8") as f:
        for line_no, raw_line in enumerate(f, start=1):
            line = raw_line.strip()
            if not line:
                continue
            stats["existing_rows"] += 1
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                stats["invalid_rows"] += 1
                print(f"[warn] keep invalid output line {line_no} when loading done ids", file=sys.stderr)
                success_or_kept_lines.append(raw_line if raw_line.endswith("\n") else raw_line + "\n")
                continue

            if obj.get("validation_failed_after_retries") is True:
                stats["migrated_failed_rows"] += 1
                obj.setdefault("failure_source", "migrated_from_old_output")
                failed_rows_to_migrate.append(obj)
                continue

            pid = obj.get("paper_id")
            if pid is not None:
                done.add(str(pid))
                stats["done_rows"] += 1
            success_or_kept_lines.append(raw_line if raw_line.endswith("\n") else raw_line + "\n")

    if failed_rows_to_migrate:
        append_jsonl(failed_output_path, failed_rows_to_migrate)
        with open(output_path, "w", encoding="utf-8") as of:
            of.writelines(success_or_kept_lines)

    return done, stats


