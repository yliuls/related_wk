def build_prompt_papers(
    papers: Sequence[Dict[str, Any]],
    max_abstract_chars: int,
) -> List[Dict[str, Any]]:
    """Build the user prompt payload.

    Candidate L3 topics are intentionally NOT repeated per paper. In this version,
    each LLM call contains papers from exactly one L2 topic, so the shared candidate
    L3 list is placed once in the system prompt.
    """
    prompt_papers: List[Dict[str, Any]] = []
    for p in papers:
        pid = str(p.get("paper_id", ""))
        prompt_papers.append(
            {
                "paper_id": pid,
                "title": norm_text(p.get("title")),
                "abstract": short_abstract(str(p.get("abstract") or ""), max_abstract_chars),
            }
        )
    return prompt_papers


def build_messages(
    prompt_papers: Sequence[Dict[str, Any]],
    candidate_l3_topics: Sequence[L3Topic],
) -> List[Dict[str, str]]:
    """Build messages for one batch.

    All papers in this call must come from the same L2 topic. The candidate L3
    topics for that L2 are placed once in the system prompt. The user prompt only
    contains paper_id/title/abstract.
    """
    system_obj: Dict[str, Any] = {
        "role": "You are an expert machine learning paper topic classifier.",
        "task": (
            "Assign each paper to one or more L3 topics from the shared candidate_L3_topics list. "
            "All papers in this request belong to the same already-known L2 topic, but the L2 topic name is not needed. "
            "Use the paper title and abstract only. Do not invent topics."
        ),
        "candidate_L3_topics": [t.to_prompt_dict() for t in candidate_l3_topics],
        "classification_rules": [
            "For each paper, select the most relevant L3 topic(s) from the shared candidate_L3_topics list.",
            "A paper may have multiple L3 topics if multiple candidates are clearly central.",
            "Usually choose 1 to 3 topics.",
            "If none are suitable, return an empty selected_L3_topics list.",
            "For each selected topic, copy BOTH id and name_en exactly from candidate_L3_topics.",
            "Do not return reason, rationale, explanation, confidence, or any extra fields.",
        ],
        "output_schema": {
            "papers": [
                {
                    "paper_id": "string",
                    "selected_L3_topics": [
                        {
                            "id": "exact candidate topic id",
                            "name_en": "exact candidate English topic name",
                        }
                    ],
                }
            ]
        },
        "output_constraints": [
            "Return valid JSON only.",
            "Do not include markdown fences.",
            "Do not include text outside the JSON object.",
        ],
    }

    user_obj: Dict[str, Any] = {
        "papers": list(prompt_papers),
    }
    system = json.dumps(system_obj, ensure_ascii=False, indent=2)
    user = json.dumps(user_obj, ensure_ascii=False, indent=2)
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]



def extract_json_object(text: str) -> Dict[str, Any]:
    """Parse a JSON object from an LLM response.

    The prompt asks for JSON only, but some models still wrap output in markdown
    fences or add short leading/trailing text. This helper keeps the script usable
    across DeepSeek/MiniMax/OpenRouter/local OpenAI-compatible services.
    """
    raw = (text or "").strip()
    if not raw:
        raise ValueError("empty LLM response")

    # Remove common markdown fences.
    if raw.startswith("```"):
        raw = re.sub(r"^```(?:json|JSON)?\s*", "", raw).strip()
        raw = re.sub(r"\s*```$", "", raw).strip()

    try:
        obj = json.loads(raw)
    except json.JSONDecodeError:
        # Fallback: extract the first balanced top-level JSON object.
        start = raw.find("{")
        if start < 0:
            raise
        depth = 0
        in_str = False
        escape = False
        end = -1
        for i in range(start, len(raw)):
            ch = raw[i]
            if in_str:
                if escape:
                    escape = False
                elif ch == "\\":
                    escape = True
                elif ch == '"':
                    in_str = False
            else:
                if ch == '"':
                    in_str = True
                elif ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
                    if depth == 0:
                        end = i + 1
                        break
        if end < 0:
            raise
        obj = json.loads(raw[start:end])

    if not isinstance(obj, dict):
        raise ValueError(f"LLM JSON root must be an object, got {type(obj).__name__}")
    return obj


def _create_chat_completion(
    client: Any,
    model: str,
    messages: List[Dict[str, str]],
    temperature: float,
    max_tokens: int,
    use_response_format: bool,
) -> Any:
    kwargs: Dict[str, Any] = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "max_tokens": max_tokens,
    }
    if use_response_format:
        kwargs["response_format"] = {"type": "json_object"}
    return client.chat.completions.create(**kwargs)


def call_llm(
    client: Any,
    model: str,
    messages: List[Dict[str, str]],
    temperature: float,
    max_tokens: int,
    response_format_mode: str,
) -> Tuple[Dict[str, Any], str, bool]:
    """Call an OpenAI-compatible Chat Completions API and return parsed JSON.

    response_format_mode:
      - on:   always use response_format={"type":"json_object"}
      - off:  never use response_format
      - auto: try with response_format first, then retry once without it if the
              endpoint rejects that parameter or returns malformed output.
    """
    if client is None:
        raise ValueError("client is None; use --dry-run to avoid API calls")

    modes: List[bool]
    if response_format_mode == "on":
        modes = [True]
    elif response_format_mode == "off":
        modes = [False]
    else:
        modes = [True, False]

    last_error: Optional[Exception] = None
    last_raw = ""
    for use_rf in modes:
        try:
            resp = _create_chat_completion(
                client=client,
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                use_response_format=use_rf,
            )
            raw_text = resp.choices[0].message.content or ""
            last_raw = raw_text
            return extract_json_object(raw_text), raw_text, use_rf
        except Exception as e:  # noqa: BLE001
            last_error = e
            # In explicit on/off mode, do not silently change behavior.
            if response_format_mode in {"on", "off"}:
                break
            # In auto mode, retry once without response_format.
            continue

    if last_raw:
        raise ValueError(f"failed to parse LLM JSON. Last raw response starts with: {last_raw[:500]!r}") from last_error
    raise RuntimeError(f"LLM call failed: {last_error}") from last_error


